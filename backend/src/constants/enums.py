from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class JobScope(str, Enum):
    standard = 'standard'
    development = 'development'
    sealed = 'sealed'
class CaseStatus(str, Enum):
    developing = 'developing'
    locked = 'locked'
    unsealing = 'unsealing'
    completed = 'completed'
